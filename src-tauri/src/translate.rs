/// Registry of in-flight translation requests that can be cancelled.
/// Keyed by a monotonically incrementing `request_id` generated by the frontend.
pub type CancellationRegistry = Arc<Mutex<HashMap<u64, oneshot::Sender<()>>>>;

/// How long to wait for the TCP/TLS connection to a provider.
pub const CONNECT_TIMEOUT: Duration = Duration::from_secs(10);

/// How long a single read may stall before the request is treated as failed.
///
/// The managed client applies this with `Client::builder().timeout(..)`. For a streaming body
/// that is an idle timeout per read rather than a cap on total duration, so a healthy stream of
/// any length keeps running while a silently dropped connection surfaces as an error that the
/// existing retry path already classifies as retryable. Non-streaming callers such as the
/// readiness probe get an overall request budget from the same value.
pub const READ_TIMEOUT: Duration = Duration::from_secs(45);

/// Builds the shared HTTP client with explicit timeouts.
///
/// `reqwest::Client::new()` applies no timeout at all, which let a stalled provider leave the UI
/// waiting on a request that would never resolve.
pub fn build_http_client() -> Client {
    Client::builder()
        .connect_timeout(CONNECT_TIMEOUT)
        .timeout(READ_TIMEOUT)
        .build()
        .unwrap_or_else(|_| Client::new())
}

/// A single delta chunk from the streaming response.
#[derive(Debug, Deserialize)]
struct StreamChoice {
    delta: StreamDelta,
}

#[derive(Debug, Deserialize)]
struct StreamDelta {
    content: Option<String>,
}

#[derive(Debug, Deserialize)]
struct StreamChunk {
    #[serde(default)]
    choices: Vec<StreamChoice>,
    usage: Option<TranslationUsage>,
}

#[derive(Clone, Serialize)]
struct TranslationChunkPayload {
    request_id: u64,
    content: String,
}

#[derive(Clone, Serialize)]
struct TranslationDonePayload {
    request_id: u64,
}

#[derive(Clone, Serialize)]
struct TranslationErrorPayload {
    request_id: u64,
    message: String,
}

#[derive(Clone, Serialize)]
struct TranslationRetryPayload {
    request_id: u64,
    attempt: u8,
}

#[derive(Clone, Serialize)]
struct TranslationUsagePayload {
    request_id: u64,
    usage: TranslationUsage,
}

#[derive(Debug, PartialEq, Eq)]
enum SseLine {
    Ignore,
    Done,
    Update(StreamUpdate),
}

#[derive(Debug, PartialEq, Eq)]
struct StreamUpdate {
    contents: Vec<String>,
    usage: Option<TranslationUsage>,
}

#[derive(Clone, Copy)]
struct RetryConfig {
    max_retries: u8,
    base_retry_ms: u64,
}

impl Default for RetryConfig {
    fn default() -> Self {
        Self {
            max_retries: 3,
            base_retry_ms: 200,
        }
    }
}

struct TranslationRequest<'a> {
    text: &'a str,
    source_lang: &'a str,
    target_lang: &'a str,
    api_key: &'a str,
    model: &'a str,
    api_base_url: &'a str,
    provider: &'a Provider,
}

struct StreamCompletion {
    translated_text: String,
    cancelled: bool,
    usage: Option<TranslationUsage>,
}

trait TranslationEventSink {
    fn emit_chunk(&mut self, request_id: u64, content: String);
    fn emit_done(&mut self, request_id: u64);
    fn emit_error(&mut self, request_id: u64, message: String);
    fn emit_retry(&mut self, request_id: u64, attempt: u8);
    fn emit_usage(&mut self, _request_id: u64, _usage: TranslationUsage) {}
    fn notify_background_success(&mut self) {}
    fn notify_background_error(&mut self, _message: &str) {}
    fn notify_background_retry(&mut self, _attempt: u8) {}
}

struct TauriEventSink<'a> {
    app: &'a AppHandle,
}

impl TranslationEventSink for TauriEventSink<'_> {
    fn emit_chunk(&mut self, request_id: u64, content: String) {
        let _ = self.app.emit(
            "translation-chunk",
            TranslationChunkPayload {
                request_id,
                content,
            },
        );
    }

    fn emit_done(&mut self, request_id: u64) {
        let _ = self
            .app
            .emit("translation-done", TranslationDonePayload { request_id });
    }

    fn emit_error(&mut self, request_id: u64, message: String) {
        let _ = self.app.emit(
            "translation-error",
            TranslationErrorPayload {
                request_id,
                message,
            },
        );
    }

    fn emit_retry(&mut self, request_id: u64, attempt: u8) {
        let _ = self.app.emit(
            "translation-retry",
            TranslationRetryPayload {
                request_id,
                attempt,
            },
        );
    }

    fn emit_usage(&mut self, request_id: u64, usage: TranslationUsage) {
        let _ = self.app.emit(
            "translation-usage",
            TranslationUsagePayload { request_id, usage },
        );
    }

    fn notify_background_success(&mut self) {
        notify_translation_background(
            self.app,
            "翻译完成",
            "最新译文已准备好。左键点击托盘图标可重新打开 Aura。",
        );
    }

    fn notify_background_error(&mut self, message: &str) {
        notify_translation_background(
            self.app,
            "翻译失败",
            format!(
                "上一次请求失败：{}",
                summarize_notification_message(message)
            ),
        );
    }

    fn notify_background_retry(&mut self, attempt: u8) {
        notify_translation_background(
            self.app,
            "正在重试翻译",
            format!(
                "Aura 正在后台重试上一次请求（第 {} 次）。",
                attempt
            ),
        );
    }
}

#[cfg(not(any(target_os = "android", target_os = "ios")))]
fn notify_translation_background(app: &AppHandle, title: &str, body: impl Into<String>) {
    if !background_notifications_enabled(app) {
        return;
    }

    let window_hidden = app
        .get_webview_window(crate::TRANSLATION_WINDOW_LABEL)
        .and_then(|window| window.is_visible().ok())
        .map(|visible| !visible)
        .unwrap_or(true);

    if !window_hidden {
        return;
    }

    let _ = app
        .notification()
        .builder()
        .title(title)
        .body(body.into())
        .show();
}

#[cfg(any(target_os = "android", target_os = "ios"))]
fn notify_translation_background(_app: &AppHandle, _title: &str, _body: impl Into<String>) {}

/// Whether the user allows background translation notifications.
///
/// This gates translation chatter only. Startup configuration failures are reported through the
/// separate `lib.rs` path and stay unconditional, because those describe a broken install rather
/// than routine translation activity.
#[cfg(not(any(target_os = "android", target_os = "ios")))]
fn background_notifications_enabled(app: &AppHandle) -> bool {
    app.try_state::<crate::ConfigState>()
        .map(|state| {
            state
                .read()
                .map(|config| config.notifications_enabled)
                .unwrap_or(true)
        })
        .unwrap_or(true)
}

fn summarize_notification_message(message: &str) -> String {
    let collapsed = message.split_whitespace().collect::<Vec<_>>().join(" ");
    let char_count = collapsed.chars().count();
    if char_count <= 120 {
        return collapsed;
    }

    collapsed.chars().take(117).collect::<String>() + "..."
}

/// Translate text using a streaming chat completions endpoint.
/// Supports any OpenAI-compatible provider (DeepSeek, OpenRouter, Ollama).
///
/// Emits request-scoped `translation-chunk` events to the frontend for each token.
/// Emits request-scoped `translation-done` when the stream is complete (including on cancellation).
/// Emits request-scoped `translation-error` on failure.
#[tauri::command]
pub async fn translate_text(
    app: AppHandle,
    client: State<'_, Client>,
    history: State<'_, crate::HistoryState>,
    registry: State<'_, CancellationRegistry>,
    text: String,
    source_lang: String,
    target_lang: String,
    api_key: String,
    model: String,
    request_id: u64,
    api_base_url: String,
    provider: Provider,
    profile_id: Option<String>,
) -> Result<(), String> {
    // Record the identity of the request that is really being sent.
    //
    // Every path funnels through here — the hotkey, the automatic clipboard monitor, an in-window
    // draft re-translation, and a history replay with an original configuration. Recording it at
    // any earlier point left the stored identity describing a request that was never dispatched,
    // so a later hotkey press could collapse the wrong result or re-send text that was already
    // translated.
    let identity = crate::interaction::RequestIdentity::from_request(
        &text,
        &source_lang,
        &target_lang,
        provider.as_str(),
        &model,
        &api_base_url,
        profile_id.as_deref(),
    );
    if let Err(err) = crate::record_request_identity(&app, identity).await {
        // Losing the identity only degrades request reuse; it must not fail a translation.
        eprintln!("[aura][identity] {err}");
    }

    // Set up cancellation channel for this request
    let (cancel_tx, cancel_rx) = oneshot::channel::<()>();
    {
        let mut reg = registry.lock().await;
        reg.insert(request_id, cancel_tx);
    }

    let request = TranslationRequest {
        text: &text,
        source_lang: &source_lang,
        target_lang: &target_lang,
        api_key: &api_key,
        model: &model,
        api_base_url: &api_base_url,
        provider: &provider,
    };

    let mut sink = TauriEventSink { app: &app };
    let result = translate_stream_with_sink(
        &mut sink,
        &client,
        cancel_rx,
        request,
        request_id,
        RetryConfig::default(),
    )
    .await;

    // Clean up registry entry regardless of outcome
    {
        let mut reg = registry.lock().await;
        reg.remove(&request_id);
    }

    match &result {
        Ok(completion) if !completion.cancelled && !completion.translated_text.is_empty() => {
            if let Err(err) = record_history_success(
                history.inner().clone(),
                &text,
                &completion.translated_text,
                &source_lang,
                &target_lang,
                &provider,
                &model,
                &api_base_url,
                profile_id.as_deref(),
                completion.usage.clone(),
            )
            .await
            {
                eprintln!("Failed to record translation history: {}", err);
            }
        }
        Err(message) => {
            if let Err(err) = record_history_error(
                history.inner().clone(),
                &text,
                message,
                &source_lang,
                &target_lang,
                &provider,
                &model,
                &api_base_url,
                profile_id.as_deref(),
            )
            .await
            {
                eprintln!("Failed to record translation history: {}", err);
            }
        }
        _ => {}
    }

    result.map(|_| ())
}

/// Internal streaming logic, separated to cleanly handle cancellation cleanup.
async fn translate_stream_with_sink<S: TranslationEventSink>(
    sink: &mut S,
    client: &Client,
    mut cancel_rx: oneshot::Receiver<()>,
    request: TranslationRequest<'_>,
    request_id: u64,
    retry_config: RetryConfig,
) -> Result<StreamCompletion, String> {
    let body = build_chat_request_body(&request);
    let url = build_chat_completions_url(request.api_base_url);
    let mut received_output = false;
    let mut translated_text = String::new();
    let mut usage: Option<TranslationUsage> = None;

    let response = {
        let mut attempt = 0;
        loop {
            let headers = match provider_headers(request.provider, request.api_key) {
                Ok(headers) => headers,
                Err(err) => {
                    sink.emit_error(request_id, err.clone());
                    sink.notify_background_error(&err);
                    return Err(err);
                }
            };

            let mut http_request = client.post(&url).header("Content-Type", "application/json");
            for (name, value) in headers {
                http_request = http_request.header(name, value);
            }
            http_request = http_request.json(&body);

            // Check cancellation while waiting for the HTTP response
            let outcome = tokio::select! {
                _ = &mut cancel_rx => {
                    sink.emit_done(request_id);
                    return Ok(StreamCompletion {
                        translated_text,
                        cancelled: true,
                        usage,
                    });
                }
                result = http_request.send() => result,
            };

            let failure = match outcome {
                Ok(resp) => {
                    if resp.status().is_success() {
                        break Ok(resp);
                    }
                    let status = resp.status();
                    let error_body = resp.text().await.unwrap_or_default();
                    let msg = format!("API error ({}): {}", status, error_body);
                    if !is_retryable_status(status) {
                        sink.emit_error(request_id, msg.clone());
                        sink.notify_background_error(&msg);
                        return Err(msg);
                    }
                    msg
                }
                Err(err) => {
                    let msg = describe_transport_error(&err);
                    if !is_retryable_transport_error(&err) {
                        sink.emit_error(request_id, msg.clone());
                        sink.notify_background_error(&msg);
                        return Err(msg);
                    }
                    msg
                }
            };

            if attempt >= retry_config.max_retries {
                sink.emit_error(request_id, failure.clone());
                sink.notify_background_error(&failure);
                break Err(failure);
            }

            let delay = retry_config.base_retry_ms * 3u64.pow(attempt as u32);
            sink.emit_retry(request_id, attempt + 1);
            sink.notify_background_retry(attempt + 1);

            // Check cancellation during the backoff delay
            tokio::select! {
                _ = &mut cancel_rx => {
                    sink.emit_done(request_id);
                    return Ok(StreamCompletion {
                        translated_text,
                        cancelled: true,
                        usage,
                    });
                }
                _ = tokio::time::sleep(tokio::time::Duration::from_millis(delay)) => {}
            }

            attempt += 1;
        }
    }?;

    let mut stream = response.bytes_stream();
    let mut buffer = String::new();

    loop {
        tokio::select! {
            // Check for cancellation signal
            _ = &mut cancel_rx => {
                sink.emit_done(request_id);
                return Ok(StreamCompletion {
                    translated_text,
                    cancelled: true,
                    usage,
                });
            }
            // Process next SSE chunk
            chunk_opt = stream.next() => {
                match chunk_opt {
                    Some(chunk_result) => {
                        let chunk = match chunk_result {
                            Ok(chunk) => chunk,
                            Err(err) => {
                                // A stalled stream is reported in the user's terms rather than as
                                // a raw transport error, so the retry prompt is understandable.
                                let msg = if err.is_timeout() {
                                    format!(
                                        "Stream stalled: no data for {}s",
                                        READ_TIMEOUT.as_secs()
                                    )
                                } else {
                                    format!("Stream error: {}", err)
                                };
                                sink.emit_error(request_id, msg.clone());
                                sink.notify_background_error(&msg);
                                return Err(msg);
                            }
                        };

                        // Normalize line endings: proxies may send \r\n
                        let text = String::from_utf8_lossy(&chunk).replace('\r', "");
                        buffer.push_str(&text);

                        // SSE format: each line starts with "data: "
                        while let Some(pos) = buffer.find('\n') {
                            let line = buffer[..pos].trim().to_string();
                            buffer = buffer[pos + 1..].to_string();

                            if line.is_empty() {
                                continue;
                            }

                            match parse_sse_line(&line) {
                                Ok(SseLine::Ignore) => {}
                                Ok(SseLine::Done) => {
                                    sink.emit_done(request_id);
                                    if received_output {
                                        sink.notify_background_success();
                                    }
                                    return Ok(StreamCompletion {
                                        translated_text,
                                        cancelled: false,
                                        usage,
                                    });
                                }
                                Ok(SseLine::Update(update)) => {
                                    if let Some(next_usage) = update.usage {
                                        usage = Some(next_usage.clone());
                                        sink.emit_usage(request_id, next_usage);
                                    }

                                    for content in update.contents {
                                        received_output = true;
                                        translated_text.push_str(&content);
                                        sink.emit_chunk(request_id, content);
                                    }
                                }
                                Err(msg) => {
                                    sink.emit_error(request_id, msg.clone());
                                    sink.notify_background_error(&msg);
                                    return Err(msg);
                                }
                            }
                        }
                    }
                    None => {
                        // Stream ended without [DONE] sentinel
                        sink.emit_done(request_id);
                        if received_output {
                            sink.notify_background_success();
                        }
                        return Ok(StreamCompletion {
                            translated_text,
                            cancelled: false,
                            usage,
                        });
                    }
                }
            }
        }
    }
}

