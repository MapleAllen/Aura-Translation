fn build_chat_request_body(request: &TranslationRequest<'_>) -> serde_json::Value {
    let system_prompt = build_system_prompt(request.source_lang, request.target_lang);
    let mut body = serde_json::json!({
        "model": request.model,
        "messages": [
            { "role": "system", "content": system_prompt },
            { "role": "user", "content": request.text }
        ],
        "temperature": 0.3,
        "stream": true
    });

    if !matches!(request.provider, Provider::Ollama) {
        body["stream_options"] = serde_json::json!({
            "include_usage": true
        });
    }

    body
}

fn build_system_prompt(source_lang: &str, target_lang: &str) -> String {
    if source_lang == "auto" {
        format!(
            "You are a professional translator. Auto-detect the source language of the following text \
             and translate it into {}. Output ONLY the translated text, nothing else. \
             Do not add any explanations, notes, or quotation marks.",
            target_lang
        )
    } else {
        format!(
            "You are a professional translator. Translate the following text from {} to {}. \
             Output ONLY the translated text, nothing else. \
             Do not add any explanations, notes, or quotation marks.",
            source_lang, target_lang
        )
    }
}

fn build_chat_completions_url(api_base_url: &str) -> String {
    format!("{}/chat/completions", api_base_url.trim_end_matches('/'))
}

fn provider_headers(
    provider: &Provider,
    api_key: &str,
) -> Result<Vec<(HeaderName, HeaderValue)>, String> {
    match provider {
        Provider::Ollama => Ok(Vec::new()),
        Provider::DeepSeek => Ok(vec![authorization_header(api_key)?]),
        Provider::OpenRouter => Ok(vec![
            authorization_header(api_key)?,
            (
                HeaderName::from_static("http-referer"),
                HeaderValue::from_static("https://github.com/MapleAllen/Aura-Translation"),
            ),
            (
                HeaderName::from_static("x-title"),
                HeaderValue::from_static("Aura Translation"),
            ),
        ]),
    }
}

fn authorization_header(api_key: &str) -> Result<(HeaderName, HeaderValue), String> {
    let value = HeaderValue::from_str(&format!("Bearer {}", api_key))
        .map_err(|err| format!("API Key 请求头无效：{}", err))?;
    Ok((HeaderName::from_static("authorization"), value))
}

fn is_retryable_status(status: StatusCode) -> bool {
    status.is_server_error()
}

fn is_retryable_transport_error(err: &reqwest::Error) -> bool {
    err.is_connect() || err.is_timeout()
}

/// Renders a transport failure together with its underlying cause.
///
/// `reqwest::Error`'s own `Display` stops at "error sending request for url (...)", which hides
/// whether the request timed out, the connection was refused, or DNS failed. The proposal requires
/// a comprehensible message for the offline, timeout, and stall cases, so the cause chain is
/// appended and de-duplicated.
fn describe_transport_error(err: &reqwest::Error) -> String {
    let mut parts = vec![err.to_string()];
    let mut source = std::error::Error::source(err);
    while let Some(cause) = source {
        let text = cause.to_string();
        if !parts.iter().any(|part| part == &text) {
            parts.push(text);
        }
        source = cause.source();
    }
    format!("Network error: {}", parts.join(": "))
}

fn parse_sse_line(line: &str) -> Result<SseLine, String> {
    if line.is_empty() {
        return Ok(SseLine::Ignore);
    }

    if line == "data: [DONE]" {
        return Ok(SseLine::Done);
    }

    let Some(json_str) = line.strip_prefix("data: ") else {
        return Ok(SseLine::Ignore);
    };

    let parsed = serde_json::from_str::<StreamChunk>(json_str)
        .map_err(|e| format!("Malformed SSE data: {}", e))?;

    let contents = parsed
        .choices
        .into_iter()
        .filter_map(|choice| choice.delta.content)
        .filter(|content| !content.is_empty())
        .collect();

    Ok(SseLine::Update(StreamUpdate {
        contents,
        usage: parsed.usage,
    }))
}

/// Cancel an in-flight translation request by its ID.
/// Sends the cancellation signal; the stream loop will emit translation-done
/// with whatever partial text has already been sent.
#[tauri::command]
pub async fn cancel_translate(
    registry: State<'_, CancellationRegistry>,
    request_id: u64,
) -> Result<(), String> {
    let mut reg = registry.lock().await;
    if let Some(sender) = reg.remove(&request_id) {
        // Ignoring send error — receiver may have already been dropped
        // if the translation completed naturally before the cancel arrived.
        let _ = sender.send(());
    }
    Ok(())
}

/// Text used by the first-run trial translation.
pub const TRIAL_SAMPLE_TEXT: &str = "Hello, world!";

/// Sink that collects the streamed result instead of emitting events.
///
/// First-run onboarding needs the translated text back at the call site, not through the
/// translation-window event pipeline, which is not mounted while Settings is in front.
struct CollectingSink {
    text: String,
    error: Option<String>,
}

impl TranslationEventSink for CollectingSink {
    fn emit_chunk(&mut self, _request_id: u64, content: String) {
        self.text.push_str(&content);
    }

    fn emit_done(&mut self, _request_id: u64) {}

    fn emit_error(&mut self, _request_id: u64, message: String) {
        if self.error.is_none() {
            self.error = Some(message);
        }
    }

    fn emit_retry(&mut self, _request_id: u64, _attempt: u8) {}
}

/// Result of the first-run trial translation shown to the user.
#[derive(Clone, Serialize)]
pub struct TrialTranslationResult {
    pub ok: bool,
    pub message: String,
    /// The translated sample, present only on success.
    pub translated_text: Option<String>,
}

fn trial_failure(message: impl Into<String>) -> TrialTranslationResult {
    TrialTranslationResult {
        ok: false,
        message: message.into(),
        translated_text: None,
    }
}

/// Validates the trial inputs before any network call, so a missing model or credential produces
/// an actionable message instead of a provider error.
fn validate_trial_inputs(provider: &Provider, api_key: &str, model: &str) -> Option<&'static str> {
    if model.trim().is_empty() {
        return Some("请先选择要使用的模型。");
    }
    if provider.requires_api_key() && api_key.trim().is_empty() {
        return Some("请先填入 API Key，或切换到本地 Ollama。");
    }
    None
}

/// Runs one real translation so onboarding ends on a working request rather than a credential
/// check alone. The provider, model, and credential supplied here are used as-is and nothing is
/// persisted, so a failed trial cannot leave a half-saved configuration behind.
#[tauri::command]
pub async fn trial_translate(
    client: State<'_, Client>,
    text: Option<String>,
    source_lang: String,
    target_lang: String,
    api_key: String,
    model: String,
    api_base_url: String,
    provider: Provider,
) -> Result<TrialTranslationResult, String> {
    let sample = text
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| TRIAL_SAMPLE_TEXT.to_string());

    if let Some(message) = validate_trial_inputs(&provider, &api_key, &model) {
        return Ok(trial_failure(message));
    }

    let request = TranslationRequest {
        text: &sample,
        source_lang: &source_lang,
        target_lang: &target_lang,
        api_key: &api_key,
        model: &model,
        api_base_url: &api_base_url,
        provider: &provider,
    };

    let mut sink = CollectingSink {
        text: String::new(),
        error: None,
    };
    // The trial is cancelled through the frontend's own timeout rather than a user cancel button,
    // so the receiver is simply dropped when the request finishes.
    let (_cancel_tx, cancel_rx) = oneshot::channel::<()>();

    let completion = translate_stream_with_sink(
        &mut sink,
        &client,
        cancel_rx,
        request,
        0,
        RetryConfig::default(),
    )
    .await;

    match completion {
        Ok(completion) if completion.cancelled => Ok(trial_failure("试译已取消。")),
        Ok(completion) if !completion.translated_text.trim().is_empty() => {
            Ok(TrialTranslationResult {
                ok: true,
                message: "试译成功。".to_string(),
                translated_text: Some(completion.translated_text),
            })
        }
        Ok(_) => Ok(trial_failure(
            "服务返回了空结果，请确认模型名称是否正确。",
        )),
        Err(err) => Ok(trial_failure(sink.error.unwrap_or(err))),
    }
}

